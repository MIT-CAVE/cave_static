/**
 * Helpers to build HTML strings (e.g. for ECharts tooltips, which render the
 * string returned by a `formatter` as HTML) without injecting markup from the
 * data. Use the `markup` tag, which escapes every value it interpolates.
 */

class SafeHtml {
  constructor(value) {
    this.value = value
  }
  toString() {
    return this.value
  }
}

const ESCAPED_CHARACTERS = {
  '&': '&amp;',
  '<': '&lt;',
  '>': '&gt;',
  '"': '&quot;',
  "'": '&#39;',
}

/**
 * Escape a value so it is shown as text when it is part of an HTML string.
 * @param {*} value
 * @returns {string}
 */
export const escapeHtml = (value) =>
  String(value).replace(/[&<>"']/g, (char) => ESCAPED_CHARACTERS[char])

/**
 * Mark a string as trusted HTML, so it is not escaped by the `markup` tag.
 * Only use it for markup that is generated by the app or by a library (e.g.
 * the `marker` of an ECharts tooltip), never for data.
 * @param {string} value
 * @returns {SafeHtml}
 */
export const safeHtml = (value) => new SafeHtml(String(value ?? ''))

const toHtml = (value) =>
  value instanceof SafeHtml
    ? value.value
    : Array.isArray(value)
      ? value.map(toHtml).join('')
      : value == null || value === false
        ? ''
        : escapeHtml(value)

/**
 * Tag for template literals that builds HTML. Values are escaped, except for the
 * results of other `markup` tags and `safeHtml`. Arrays are joined, and `null`,
 * `undefined` and `false` are ignored, so lists can be built with `map` and
 * `filter` without a `join`.
 *
 * The result is not a string. Use `.toString()` where a string is expected.
 * @example
 * markup`<b>${name}</b> ${safeHtml(marker)}`.toString()
 * @param {TemplateStringsArray} strings
 * @param {...*} values
 * @returns {SafeHtml}
 */
export const markup = (strings, ...values) =>
  new SafeHtml(
    strings.reduce(
      (result, string, index) =>
        result + string + (index < values.length ? toHtml(values[index]) : ''),
      ''
    )
  )
